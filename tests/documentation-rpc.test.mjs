import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {createCaneWeighingDb} from '../supabase/tests/helpers/cane-weighing-db.mjs';

test('Documentation: real migrations, private files, links, optional boletos, revisions, history and isolation', async () => {
 const {db, ids, setActor} = await createCaneWeighingDb();
 const rpc = async (resource, action, payload = {}) => (await db.query('SELECT public.billing_rpc($1,$2,$3::jsonb) result', [resource, action, JSON.stringify(payload)])).rows[0].result;
 const docs = (action, payload) => rpc('documentation', action, payload);
 const denied = (fn, code) => assert.rejects(fn, e => e.code === code, `Expected ${code}`);
 const providerInput = {documentType:'CNPJ',document:'11222333000181',legalName:'Oficina de teste',tradeName:'',street:'',number:'',complement:'',district:'',city:'',state:'',zipCode:'',phone:'',email:''};
 try {
  await db.exec('RESET ROLE; ALTER TABLE storage.objects ADD COLUMN metadata jsonb;');
  await setActor();
  const provider = (await rpc('service-providers','save',providerInput)).provider;
  const requester = (await rpc('signatures','save',{name:'Solicitante documental',role:'requester'})).signature;
  const request = (await rpc('service-requests','create',{requestId:randomUUID(),requesterSignatureId:requester.id,providerId:provider.id,items:[{description:'Conserto do trator',application:'Trator 10'}],notes:'',attachmentIds:[],serviceValue:null,returnDate:null})).request;
  const material=(await rpc('materials','save',{name:'Filtro documental',internalCode:'DOC-001',unit:'UN',application:'Trator'})).material;
  const quote=(await rpc('quotations','save',{title:'Compra documental',number:'DOC-001',requestDate:'2026-10-22',requesterSignatureId:requester.id,notes:'',items:[{id:randomUUID(),materialId:material.id,quantity:'2',notes:''}],providers:[{id:randomUUID(),providerId:provider.id,values:{},notes:'',sentAt:null}]})).quote;
  await rpc('quotations','record-negotiation',{id:quote.id,requestId:randomUUID(),quotationProviderId:quote.providers[0].id,quotationItemId:quote.items[0].id,unitPrice:'10',availableQuantity:'2',discountType:'none',discountValue:'0',notes:''});
  await rpc('quotations','award-item',{id:quote.id,quotationProviderId:quote.providers[0].id,quotationItemId:quote.items[0].id});
  const order=(await rpc('quotations','finalize',{id:quote.id})).purchaseOrders[0];
  assert.equal((await docs('context',{type:'quotation',id:quote.id})).source.label,'Cotação DOC-001');
  assert.ok((await docs('context',{type:'order',id:order.id})).source.label.includes(order.number));
  assert.equal((await docs('sources')).sources.length,3,'All source types can be listed together');
  const source = {type:'service',id:request.id};
  const base = {id:randomUUID(),expectedRevision:0,kind:'invoice',title:'Nota do conserto',documentNumber:'100',issuedOn:'2026-10-22',dueOn:'',amount:'150.25',providerId:'',companyId:ids.company,parentId:'',notes:'Trator 10',sources:[source],fileIds:[]};
  assert.equal((await docs('context',source)).documents.length,0);
  assert.deepEqual((await docs('list')).pending,[],'No boleto is required implicitly');
  await docs('expectation',{source,kind:'invoice',required:true,dueOn:'2026-01-01',notes:'Solicitar ao fornecedor'});
  let pending=(await docs('list')).pending;
  assert.equal(pending[0].reason,'missing');assert.equal(pending[0].overdue,true);
  await denied(()=>docs('save',base),'23514');
  const prepared=(await docs('prepare-upload',{documentId:base.id,fileName:'nota.pdf',contentType:'application/pdf',size:100})).file;
  await denied(()=>docs('prepare-upload',{documentId:base.id,fileName:'x.svg',contentType:'image/svg+xml',size:100}),'22023');
  await denied(()=>docs('prepare-upload',{documentId:base.id,fileName:'x.pdf',contentType:'application/pdf',size:10485761}),'22023');
  await db.query("INSERT INTO storage.objects(bucket_id,name) VALUES('billing-documentation',$1)",[prepared.path]);
  base.fileIds=[prepared.id];
  await denied(()=>docs('save',base),'23514');
  await db.exec('RESET ROLE');
  await db.query("UPDATE storage.objects SET metadata=$1 WHERE name=$2",[JSON.stringify({size:100,mimetype:'application/pdf'}),prepared.path]);
  await setActor();
  const document=(await docs('save',base)).document;
  assert.equal(document.providerId,provider.id,'Supplier is derived on the server');
  assert.equal(document.amount,'150.25');assert.equal(document.files.length,1);assert.equal(document.sources[0].id,request.id);
  assert.equal(document.status,'review');
  const list=await docs('list',{search:'Trator 10'});
  assert.equal(list.total,1);assert.equal(list.documents[0].id,base.id);
  assert.equal((await docs('list',{search:'nota.pdf'})).total,1);
  assert.equal((await docs('context',source)).documents.length,1);
  const quoteDocument={...base,expectedRevision:1,kind:'budget',sources:[{type:'quotation',id:quote.id}],providerId:provider.id};
  await docs('save',quoteDocument);
  assert.equal((await docs('context',{type:'order',id:order.id})).documents[0].id,base.id,'Order reuses quotation documents without duplicating them');
  await docs('save',{...base,expectedRevision:2});
  assert.equal((await docs('save',{...base,expectedRevision:2})).document.id,base.id,'Identical retry does not create a duplicate');
  await denied(()=>docs('save',{...base,title:'Outros dados'}),'23505');
  await docs('review',{id:base.id,expectedRevision:3,status:'verified',note:'Conferido',replacementId:''});
  assert.deepEqual((await docs('list')).pending,[],'Conferred invoice satisfies expectation without boleto');
  await denied(()=>db.query("UPDATE public.billing_documents SET title='forged' WHERE id=$1",[base.id]),'42501');
  await db.query("DELETE FROM storage.objects WHERE name=$1",[prepared.path]);
  assert.equal((await db.query('SELECT count(*)::int n FROM storage.objects WHERE name=$1',[prepared.path])).rows[0].n,1,'Consumed files cannot be removed');
  await denied(()=>docs('save',{...base,expectedRevision:4,fileIds:[]}),'23514');
  await denied(()=>docs('save',{...base,id:randomUUID(),sources:[{type:'service',id:randomUUID()}]}),'P0002');
  await denied(()=>docs('save',{...base,id:randomUUID(),companyId:ids.otherCompany}),'23514');
  const makeChild=async(kind,title,reference=source)=>{
   const input={...base,id:randomUUID(),expectedRevision:0,kind,title,providerId:provider.id,parentId:base.id,documentNumber:'',amount:'75.12',dueOn:'2026-11-10',sources:[reference]};
   const f=(await docs('prepare-upload',{documentId:input.id,fileName:'boleto.png',contentType:'image/png',size:40})).file;
   await db.query("INSERT INTO storage.objects(bucket_id,name) VALUES('billing-documentation',$1)",[f.path]);
   await db.exec('RESET ROLE');await db.query('UPDATE storage.objects SET metadata=$1 WHERE name=$2',[JSON.stringify({size:40,mimetype:'image/png'}),f.path]);await setActor();
   input.fileIds=[f.id];return (await docs('save',input)).document;
  };
  const boleto1=await makeChild('boleto','Parcela 1');const boleto2=await makeChild('boleto','Parcela 2');
  const detail=await docs('get',{id:base.id});assert.equal(detail.children.length,2);assert.equal(detail.document.status,'verified','Boletos never settle or change the invoice');
  assert.equal(detail.history.length,4);assert.equal(detail.history[1].actorName,'AGRISUL');
  await docs('expectation',{source,kind:'boleto',required:true,dueOn:'',notes:''});
  assert.ok((await docs('list')).pending.some(p=>p.kind==='boleto'&&p.reason==='review'));
  await docs('expectation',{source,kind:'boleto',required:false,dueOn:'',notes:'Pagamento por Pix'});
  await docs('review',{id:boleto1.id,expectedRevision:1,status:'divergent',note:'Valor incorreto',replacementId:''});
  await docs('review',{id:boleto1.id,expectedRevision:2,status:'replaced',note:'Nova parcela recebida',replacementId:boleto2.id});
  assert.equal((await docs('get',{id:boleto1.id})).document.replacementId,boleto2.id);
  await denied(()=>docs('review',{id:boleto1.id,expectedRevision:3,status:'verified',note:'',replacementId:''}),'23514');
  const requestDocuments=[];
  for(const [kind,title,reference] of [['service_request','Solicitação de serviço',source],['purchase_request','Solicitação de compras',{type:'order',id:order.id}]]){
   await docs('expectation',{source:reference,kind,required:true,dueOn:'',notes:''});
   assert.ok((await docs('list')).pending.some(p=>p.kind===kind&&p.reason==='missing'));
   const saved=await makeChild(kind,title,reference);requestDocuments.push(saved.id);
   assert.equal((await docs('get',{id:saved.id})).document.kind,kind);
   assert.equal((await docs('list',{kind})).total,1,'New request kinds support server-side filtering');
   assert.ok((await docs('context',reference)).documents.some(d=>d.id===saved.id));
   assert.ok((await docs('list')).pending.some(p=>p.kind===kind&&p.reason==='review'));
   await docs('review',{id:saved.id,expectedRevision:1,status:'verified',note:'Conferido',replacementId:''});
   assert.ok(!(await docs('list')).pending.some(p=>p.kind===kind),'Conferred request satisfies its document expectation');
  }
  await denied(()=>docs('expectation',{source,kind:'unsupported',required:true,dueOn:'',notes:''}),'22023');
  await denied(()=>docs('save',{...base,id:randomUUID(),kind:'unsupported'}),'22023');
  await setActor(ids.reader);await denied(()=>docs('list'),'42501');
  await db.exec('RESET ROLE');
  await db.query("UPDATE public.billing_access_profiles SET permissions=ARRAY['documentation.read'] WHERE id=$1",[ids.readerProfile]);
  await setActor(ids.reader);assert.ok((await docs('list')).total>0);
  assert.equal((await docs('options')).canManage,false);
  await denied(()=>docs('prepare-upload',{documentId:randomUUID(),fileName:'reader.pdf',contentType:'application/pdf',size:100}),'42501');
  await setActor(ids.otherOwner);assert.equal((await docs('list')).total,0);
  await denied(()=>docs('get',{id:base.id}),'P0002');await denied(()=>docs('context',source),'P0002');
  for(const id of requestDocuments)await denied(()=>docs('get',{id}),'P0002');
  assert.equal((await db.query('SELECT * FROM public.billing_documents')).rows.length,0);
  assert.equal((await db.query('SELECT * FROM storage.objects WHERE name=$1',[prepared.path])).rows.length,0);
  await setActor(null);await denied(()=>docs('list'),'28000');
  await db.exec('RESET ROLE');
  await denied(()=>db.query('DELETE FROM public.billing_service_requests WHERE owner_id=$1 AND id=$2',[ids.owner,request.id]),'23503');
  await db.query('DELETE FROM auth.users WHERE id=$1',[ids.owner]);
  assert.equal((await db.query('SELECT count(*)::int n FROM public.billing_documents WHERE owner_id=$1',[ids.owner])).rows[0].n,0,'Whole-account cleanup resolves deferred owner-scoped constraints');
 } finally {await db.close();}
});
